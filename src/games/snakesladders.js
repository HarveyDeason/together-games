import { LINKS, LAST_SQUARE, SQUARE_TEXT } from './snakesladders-board.js';
import {
  buildWorld, makeToken, placeToken, dieFace,
  cameraTransform, cameraTarget, ZOOM
} from './snakesladders-render.js';

export const meta = { id: 'snakesladders', name: 'Snakes & Ladders', seats: 2 };

export function createInitialState(opts = {}) {
  return {
    pos0: 0,
    pos1: 0,
    turn: opts.first ?? 0,
    moves: 0,
    die: null,
    from: null,
    via: null,
    to: null,
    seat: null
  };
}

export function getStatus(state) {
  if (state.pos0 === LAST_SQUARE) return { phase: 'won', winner: 0, whoseTurn: null, line: null };
  if (state.pos1 === LAST_SQUARE) return { phase: 'won', winner: 1, whoseTurn: null, line: null };
  return { phase: 'playing', winner: null, whoseTurn: state.turn, line: null };
}

/** Which seat should roll first in the NEXT game.
 *
 *  The previous starter is derived rather than stored: seats alternate every
 *  move, so after an even number of moves it is the starter's turn again. That
 *  keeps `first` out of the database, whose rules reject unknown keys. Same
 *  reasoning as the Tic Tac Toe module. */
export function nextStarter(state) {
  const previousStarter = state.moves % 2 === 0 ? state.turn : 1 - state.turn;
  return 1 - previousStarter;
}

export function applyAction(state, action, seat) {
  if (getStatus(state).phase !== 'playing') return { error: 'game-over' };
  if (seat !== state.turn) return { error: 'not-your-turn' };
  if (!action || action.type !== 'roll') return { error: 'unknown-action' };

  // The die is generated by the caller, never here: applyAction must stay pure
  // so both clients can run it on the same action and agree.
  const die = action.die;
  if (!Number.isInteger(die) || die < 1 || die > 6) return { error: 'bad-die' };

  const key = seat === 0 ? 'pos0' : 'pos1';
  const from = state[key];
  const landed = from + die;

  // You must finish exactly on the last square. An overshoot does not move you
  // — but it still passes the turn, or the game deadlocks near the end.
  if (landed > LAST_SQUARE) {
    return {
      state: {
        ...state,
        turn: 1 - seat,
        moves: state.moves + 1,
        die,
        seat,
        from,
        via: null,
        to: from
      }
    };
  }

  // Applied once, never looped: no destination is also a source, so a ladder
  // cannot deposit you on the head of a queue.
  const linked = LINKS[landed];
  const to = linked ?? landed;

  return {
    state: {
      ...state,
      [key]: to,
      turn: 1 - seat,
      moves: state.moves + 1,
      die,
      seat,
      from,
      via: linked === undefined ? null : landed,
      to
    }
  };
}

const STEP_MS = 90;
const LINK_MS = 260;
const FOLLOW_KEY = 'together-games.snakesladders.follow';

function readFollowPreference() {
  // Zoomed in by default: the whole point is that the board is hard to read
  // at full width on a phone.
  try { return localStorage.getItem(FOLLOW_KEY) !== '0'; } catch { return true; }
}

/** Point the camera at whatever matters right now. */
function moveCamera(world, immediate = false) {
  const scale = world.following ? ZOOM : 1;
  const square = world.following
    ? cameraTarget(world.state ?? { pos0: 0, pos1: 0, turn: 0 }, world.mySeat, world.movingSeat ?? null)
    : null;
  const at = square ? world.squarePos[square] : { x: 900, y: 700 };

  world.camera.setAttribute('transform', cameraTransform(at.x, at.y, scale));
  world.camButton.textContent = world.following ? 'Zoom out' : 'Follow';
  world.camButton.setAttribute('aria-pressed', String(world.following));
  if (immediate) world.svg.setAttribute('data-cam', 'snap');
  else world.svg.removeAttribute('data-cam');
}

const prefersReducedMotion = () =>
  typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches;

/** Did this move end by taking a ladder or a cable?
 *
 *  Firebase omits keys whose value is null, so a plain move arrives from the
 *  database with `via` UNDEFINED, not null. Comparing against null made every
 *  ordinary move wait for a link animation that was never coming. */
export function tookLink(state) {
  return state.via != null && state.via !== state.to;
}

/** Draws the game.
 *
 *  Unlike the Tic Tac Toe module this does NOT rebuild on every update: the
 *  world is a hundred isometric blocks and redrawing them on a phone every time
 *  a die lands would stutter. The scene is built on the first call and kept on
 *  the container; afterwards only the tokens, the die and the caption change.
 *  The game contract allows this — render may do as it likes so long as it
 *  draws the state it is given. */
export function render(state, el, { mySeat, names, onAction }) {
  const doc = el.ownerDocument ?? globalThis.document;
  let world = el.__sl;

  if (!world) {
    el.innerHTML = '';
    const { svg, camera, squarePos, tokenLayer } = buildWorld(doc);

    // The board is wider than a phone, so it ships zoomed in and follows the
    // action. The stage wraps the svg so the camera button can sit over it.
    const stage = doc.createElement('div');
    stage.className = 'sl-stage';
    stage.appendChild(svg);

    const camButton = doc.createElement('button');
    camButton.type = 'button';
    camButton.className = 'sl-cam';
    camButton.addEventListener('click', () => {
      world.following = !world.following;
      try { localStorage.setItem(FOLLOW_KEY, world.following ? '1' : '0'); } catch { /* private mode */ }
      moveCamera(world, true);
    });
    stage.appendChild(camButton);
    el.appendChild(stage);

    const tokens = { 0: makeToken(doc, 0), 1: makeToken(doc, 1) };
    tokenLayer.appendChild(tokens[0]);
    tokenLayer.appendChild(tokens[1]);

    const bar = doc.createElement('div');
    bar.className = 'sl-bar';

    const die = doc.createElement('span');
    die.className = 'sl-die';
    die.setAttribute('aria-live', 'polite');

    const rollButton = doc.createElement('button');
    rollButton.className = 'btn sl-roll';
    rollButton.type = 'button';
    rollButton.textContent = 'Roll';
    rollButton.addEventListener('click', () => {
      if (rollButton.disabled) return;
      rollButton.disabled = true;           // a second tap before the next
                                            // render would only be rejected
      // The die is generated here, never inside applyAction, which must stay
      // pure so both clients agree on the same action.
      const sent = world.onAction({ type: 'roll', die: 1 + Math.floor(Math.random() * 6) });
      // If the write fails there is no snapshot to re-render from, so the
      // button would stay disabled and the player could never roll again.
      Promise.resolve(sent).catch(() => {}).then(() => setControls(world));
    });

    const caption = doc.createElement('p');
    caption.className = 'sl-caption';

    bar.appendChild(die);
    bar.appendChild(rollButton);
    el.appendChild(bar);
    el.appendChild(caption);

    world = {
      doc, svg, camera, camButton, squarePos, tokens, die, rollButton, caption,
      shown: { 0: 0, 1: 0 }, busy: false, generation: 0, animatedKey: null,
      following: readFollowPreference(), lookingAt: null
    };
    el.__sl = world;
    placeToken(tokens[0], squarePos, 0, 0);
    placeToken(tokens[1], squarePos, 0, 1);
    showDie(world, null);
    moveCamera(world, true);
  }

  // Everything downstream reads the LATEST state off `world`, never a value
  // closed over when an animation started. A stale closure used to move the
  // tokens back and disable Roll on a turn that had already passed.
  world.state = state;
  world.mySeat = mySeat;
  world.names = names;
  world.onAction = onAction;

  animate(world);
}

function showDie(world, value) {
  world.die.innerHTML = '';
  world.die.appendChild(dieFace(world.doc, value ?? null));
  world.die.setAttribute('aria-label', value ? `Rolled ${value}` : 'No roll yet');
}

function setControls(world) {
  const status = getStatus(world.state);
  const mine = status.phase === 'playing' && world.mySeat !== null && status.whoseTurn === world.mySeat;
  world.rollButton.disabled = world.busy || !mine;
}

/** The caption is written when the move LANDS, not when it starts, so the joke
 *  does not arrive before the token does. It is always written — including to
 *  the empty string — or a line sticks around and gets attributed to a later
 *  move, or survives into the next game. */
function setCaption(world) {
  const s = world.state;
  const status = getStatus(s);

  if (status.phase === 'won') {
    world.caption.textContent = status.winner === world.mySeat
      ? 'You got there.'
      : `${world.names[status.winner]} got there first.`;
    return;
  }
  if (s.seat == null) { world.caption.textContent = ''; return; }
  if (s.to === s.from) { world.caption.textContent = 'Too far. You need the exact roll.'; return; }

  const landed = s.via ?? s.to;
  world.caption.textContent = SQUARE_TEXT[landed] ?? '';
}

function settle(world) {
  const s = world.state;
  placeToken(world.tokens[0], world.squarePos, s.pos0, 0);
  placeToken(world.tokens[1], world.squarePos, s.pos1, 1);
  world.shown = { 0: s.pos0, 1: s.pos1 };
  world.busy = false;
  world.movingSeat = null;
  moveCamera(world);
  showDie(world, s.die);
  setCaption(world);
  setControls(world);
}

/** Walk the moving token square by square, then drop it down the link, so the
 *  other phone sees the same journey rather than a token teleporting.
 *
 *  Every chain carries a generation. The room listens to the whole game node,
 *  so a write to `game/scored` after a win re-delivers the same state and used
 *  to start a second chain fighting the first — on the winning move. */
function animate(world) {
  const s = world.state;
  const key = `${s.moves}:${s.seat ?? 'x'}`;

  if (world.animatedKey === key) { settle(world); return; }
  world.animatedKey = key;
  const generation = ++world.generation;
  const superseded = () => world.generation !== generation;

  if (s.seat == null || s.from == null || prefersReducedMotion() || typeof setTimeout !== 'function') {
    settle(world);
    return;
  }

  world.busy = true;
  setControls(world);

  const landed = s.via ?? s.to;
  let square = s.from;

  const hop = () => {
    if (superseded()) return;
    if (square < landed) {
      square += 1;
      placeToken(world.tokens[s.seat], world.squarePos, square, s.seat);
      world.movingSeat = s.seat;
      world.shown[s.seat] = square;
      moveCamera(world);
      setTimeout(hop, STEP_MS);
      return;
    }
    if (tookLink(s)) {
      setTimeout(() => {
        if (superseded()) return;
        placeToken(world.tokens[s.seat], world.squarePos, s.to, s.seat);
        world.shown[s.seat] = s.to;
        moveCamera(world);
        settle(world);
      }, LINK_MS);
      return;
    }
    settle(world);
  };
  hop();
}
