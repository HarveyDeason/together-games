import { LINKS, LAST_SQUARE } from './snakesladders-board.js';

export const meta = { id: 'snakesladders', name: 'Snakes & Ladders', seats: 2 };

export function createInitialState(opts = {}) {
  return {
    pos0: 0,
    pos1: 0,
    turn: opts.first ?? 0,
    moves: 0,
    die: null,
    from: null,
    via: null,
    to: null,
    seat: null
  };
}

export function getStatus(state) {
  if (state.pos0 === LAST_SQUARE) return { phase: 'won', winner: 0, whoseTurn: null, line: null };
  if (state.pos1 === LAST_SQUARE) return { phase: 'won', winner: 1, whoseTurn: null, line: null };
  return { phase: 'playing', winner: null, whoseTurn: state.turn, line: null };
}

/** Which seat should roll first in the NEXT game.
 *
 *  The previous starter is derived rather than stored: seats alternate every
 *  move, so after an even number of moves it is the starter's turn again. That
 *  keeps `first` out of the database, whose rules reject unknown keys. Same
 *  reasoning as the Tic Tac Toe module. */
export function nextStarter(state) {
  const previousStarter = state.moves % 2 === 0 ? state.turn : 1 - state.turn;
  return 1 - previousStarter;
}

export function applyAction(state, action, seat) {
  if (getStatus(state).phase !== 'playing') return { error: 'game-over' };
  if (seat !== state.turn) return { error: 'not-your-turn' };
  if (!action || action.type !== 'roll') return { error: 'unknown-action' };

  // The die is generated by the caller, never here: applyAction must stay pure
  // so both clients can run it on the same action and agree.
  const die = action.die;
  if (!Number.isInteger(die) || die < 1 || die > 6) return { error: 'bad-die' };

  const key = seat === 0 ? 'pos0' : 'pos1';
  const from = state[key];
  const landed = from + die;

  // You must finish exactly on the last square. An overshoot does not move you
  // — but it still passes the turn, or the game deadlocks near the end.
  if (landed > LAST_SQUARE) {
    return {
      state: {
        ...state,
        turn: 1 - seat,
        moves: state.moves + 1,
        die,
        seat,
        from,
        via: null,
        to: from
      }
    };
  }

  // Applied once, never looped: no destination is also a source, so a ladder
  // cannot deposit you on the head of a queue.
  const linked = LINKS[landed];
  const to = linked ?? landed;

  return {
    state: {
      ...state,
      [key]: to,
      turn: 1 - seat,
      moves: state.moves + 1,
      die,
      seat,
      from,
      via: linked === undefined ? null : landed,
      to
    }
  };
}
